rows = []
with open("archive/novakid_rewrite_2.tsv", encoding="utf-8-sig") as f:
    r = csv.DictReader(f, delimiter="\t")
    for row in r:
        rows.append(row)

out = []
unmatched = []
for row in rows:
    old = row["korean"]
    new = MAP.get(old)
    if new is None:
        unmatched.append(row)
        continue
    if new == old:
        continue
    note = NOTES.get(old, "")
    out.append((row["asset"], row["pointer"], old, new, note))

print("total rows:", len(rows))
print("changed:", len(out))
print("unmatched (need manual check):", len(unmatched))
for u in unmatched:
    print("UNMATCHED:", u["asset"], "|", u["pointer"], "|", u["korean"])

