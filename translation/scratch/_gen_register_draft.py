w = csv.writer(open('_register_draft.tsv', 'w', encoding='utf-8', newline=''), delimiter='\t')
w.writerow(['asset', 'path', 'old', 'new', 'en'])
n = 0
for r in rows[1:]:
    if r[0] in ASSETS and POLITE.search(r[3]):
        new = convert(r[3])
        if new != r[3]:
            w.writerow([r[0], r[1], r[3], new, r[2][:60]])
            n += 1
print('generated', n)
