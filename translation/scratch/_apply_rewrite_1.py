def main():
    rows = []
    with open("archive/glitch_rewrite_1.tsv", encoding="utf-8-sig") as f:
        r = csv.DictReader(f, delimiter="\t")
        for row in r:
            rows.append(row)

    out_rows = []
    unmapped = []
    for row in rows:
        ko = row["korean"]
        if ko in SKIP_UNCHANGED:
            continue
        new_ko = MAP.get(ko)
        if new_ko is None:
            unmapped.append((row["asset"], row["pointer"], ko))
            continue
        if new_ko == ko:
            continue
        out_rows.append((row["asset"], row["pointer"], ko, new_ko, NOTES.get(ko, "")))

    print("total input rows:", len(rows))
    print("changed rows:", len(out_rows))
    print("unmapped (need attention):", len(unmapped))
    for a, p, ko in unmapped:
        print("UNMAPPED:", a, p, ko)

    with open("archive/glitch_rewrite_1_output.tsv", "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(["asset", "pointer", "old_korean", "new_korean", "note"])
        for row in out_rows:
            w.writerow(row)
    print("wrote glitch_rewrite_1_output.tsv")


