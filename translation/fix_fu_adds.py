def dump_cell(t):
    return '"' + t.replace('"', '""') + '"' if ('\n' in t or '"' in t or '\t' in t or t != t.strip()) else t

file_rows = {}; file_ids = {}
for fn in glob.glob('translations/rest_*.tsv'):
    with open(fn, encoding='utf-8-sig', newline='') as f:
        rows = [r for r in csv.reader(f, delimiter='\t') if r]
        file_rows[fn] = rows
        file_ids[fn] = {r[0] for r in rows if r and r[0].isdigit()}

# remove duplicates if id already exists
for i in ADD:
    for fn, ids in file_ids.items():
        if i in ids:
            print('already exists:', i, fn); break

for i, txt in ADD.items():
    ti = int(i); best = None; bf = -1
    for fn, ids in file_ids.items():
        lows = [int(x) for x in ids if int(x) < ti]
        if lows and max(lows) > bf:
            bf = max(lows); best = fn
    file_rows[best].append([i, txt]); file_ids[best].add(i)
    print('add', i, '->', best.split('/')[-1])

for fn, rows in file_rows.items():
    rows.sort(key=lambda r: int(r[0]) if r and r[0].isdigit() else 0)
    with open(fn, 'w', encoding='utf-8-sig', newline='') as f:
        for r in rows:
            f.write('\t'.join(dump_cell(c) for c in r) + '\n')
print('done', len(ADD))
