def emit(leaf, arr, name):
    rows = list(csv.DictReader(open("data/uncov_batch/" + leaf + ".tsv", encoding="utf-8-sig"), delimiter="\t"))
    assert len(rows) == len(arr), (leaf, len(rows), len(arr))
    w = csv.writer(open("data/_uncov_ko_" + name + ".tsv", "w", encoding="utf-8", newline=""), delimiter="\t")
    w.writerow(["en", "ko"])
    for r, ko in zip(rows, arr):
        w.writerow([r["en"], ko])
    print(name, len(arr))


