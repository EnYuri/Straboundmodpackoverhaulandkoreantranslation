rows = []
with open("archive/glitch_rewrite_3.tsv", encoding="utf-8-sig") as f:
    r = csv.DictReader(f, delimiter="\t")
    for row in r:
        rows.append(row)

out = []
unmapped = []
for row in rows:
    ko = row["korean"]
    if ko in NO_CHANGE:
        continue
    new = MAP.get(ko)
    if new is None:
        unmapped.append((row["asset"], row["pointer"], ko))
        continue
    if new == ko:
        continue
    out.append((row["asset"], row["pointer"], ko, new))

